    private void btnCalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularActionPerformed
        
        try{
            String strConsumo = inConsumo.getText();
            String strCouvert = inCouvert.getText();
            double consumo = Double.valueOf(strConsumo);
            double couvert = Double.valueOf(strCouvert);
            int numeroDePessoas = selDividir.getSelectedIndex();
            int taxa = 0;
            double total = 0;
                    
            if (rbTaxaNao.isSelected()) {
                taxa = 0;
            } else if (rbTaxaSim.isSelected()) {
                taxa = 10;
            }
            
            if (taxa == 0){
                total = consumo;
            }
            if (taxa == 10){
                total = consumo + ((consumo/100)*10); 
                total += couvert;
            }
            
            double valorPorPessoa = total/(numeroDePessoas+1);
            String strTotal = String.valueOf(total%2f);
            String strValorPorPessoa = String.valueOf(valorPorPessoa%2f);
            
            inCustoTotal.setText(strTotal);
            inValorPorPessoa.setText(strValorPorPessoa);
            
        }
        catch(Exception e){
            JOptionPane.showMessageDialog(rootPane, "Preencha todos os campos devidamente!");
        }
    }//GEN-LAST:event_btnCalcularActionPerformed

